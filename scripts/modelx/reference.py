AXES={'side':([1,0,0],[0,0,1],[0,-1,0]),'front':([0,1,0],[0,0,1],[1,0,0]),
      'rear':([0,-1,0],[0,0,1],[-1,0,0]),'top':([-1,0,0],[0,-1,0],[0,0,1])}
# Each entry constrains a measured pixel coordinate of a physical landmark.
def fit(view):
    marks={
    'side':[(0,-.98,.378,313,526),(2.965,-.98,.378,1110,525),(0,-.87,0,313,628),
            (2.965,-.87,0,1110,626),(-1.07,0,.58,73,None),(3.97,0,.65,1318,None),(1.,0,1.68,None,153)],
    'front':[(2.965,.87,0,992,664),(2.965,-.87,0,405,664),(2.94,1,.45,1037,None),(2.94,-1,.45,352,None),
             (1.,0,1.68,694,109),(2.29,1.105,1.16,1040,None),(2.29,-1.105,1.16,351,None)],
    'rear':[(0,.87,0,420,670),(0,-.87,0,966,670),(0,1,.54,368,None),(0,-1,.54,1018,None),(1.,0,1.68,693,122),
            (2.29,1.105,1.16,407,None),(2.29,-1.105,1.16,982,None)],
    'top':[(3.97,0,.65,157,389),(-1.07,0,.65,1230,389),(1.35,-.986,.91,None,176),
           (1.35,.986,.91,None,599),(2.29,-1.105,1.16,521,134),(2.29,1.105,1.16,521,626)]}[view]
    axes=np.array(AXES[view])
    def errors(params):
        dist,f,aspect,h,k,u,v=params
        residual=[]
        for x,y,z,px,py in marks:
            a,b,c=axes @ [x,y,z]
            if px is not None: residual.append(u+f*(a-h)/(dist-c)-px)
            if py is not None: residual.append(v-f*aspect*(b-k)/(dist-c)-py)
        # Regularise the optical centre in the absence of EXIF / lens data.
        return residual+[(u-688)*.12,(v-384)*.12,(aspect-1)*28]
    init={'side':[10,2450,1,1.4,.8,688,384],'front':[16,4400,1,0,.82,688,384],
          'rear':[12,3900,1,0,.8,688,384],'top':[12,2400,1,-1.45,0,688,384]}[view]
    sol=least_squares(errors,init,bounds=([5,900,.80,-4,-2,550,240],[45,16000,1.25,4,2,830,540]))
    d,f,aspect,h,k,u,v=sol.x
    return dict(location=list(axes.T @ [h,k,d]),right=AXES[view][0],up=AXES[view][1],
                back=AXES[view][2],focal_px=f,aspect=aspect,cx=u,cy=v,
                rms_px=float(np.sqrt(np.mean(np.square(errors(sol.x)[:-3])))))
